def build_global_seed_docs() -> List[Dict[str, Any]]:
    """Build RAG-ready document records covering all 12 countries, pathways, thresholds, and official applicant notes."""
    docs: List[Dict[str, Any]] = []
    for c in COUNTRIES_CATALOG:
        notes_list = c.get("applicant_notes") or []
        overview_text = (
            f"{c['name']} ({c['code']}) — Official Immigration Authority: {c['authority']} ({c['official_portal']}). "
            f"{c['summary']} "
            f"Official Applicant Notes: {' '.join(notes_list)}"
        )
        docs.append(
            {
                "slug": f"country-{c['id']}-overview",
                "country_id": c["id"],
                "country_name": c["name"],
                "track": c["name"],
                "title": f"{c['name']} — Official Immigration Portal & Requirements",
                "url": c["official_portal"],
                "site_last_modified": "2026-11-09",
                "alert_text": notes_list[0] if notes_list else "",
                "content_text": overview_text,
            }
        )
        for p in c["pathways"]:
            steps_summary = " ".join(f"Step: {s['title']} ({s['description']})" for s in p["stages"])
            p_text = (
                f"{c['name']} Pathway: {p['name']} ({p['category']}). "
                f"Permanent Residence Path: {p['leads_to_pr']}. "
                f"Thresholds: {p['threshold_label']}. "
                f"Job Offer Required: {'Yes' if p['requires_job_offer'] else 'No'}. "
                f"{p['summary']} {steps_summary}"
            )
            docs.append(
                {
                    "slug": f"pathway-{p['id']}",
                    "country_id": c["id"],
                    "country_name": c["name"],
                    "track": c["name"],
                    "title": f"{c['name']}: {p['name']}",
                    "url": p["official_url"],
                    "site_last_modified": "2026-11-09",
                    "alert_text": "",
                    "content_text": p_text,
                }
            )
    return docs
